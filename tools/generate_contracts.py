"""Generate pydantic models from the target's vendored JSON Schemas.

Chain (black-box, separate repo — see docs/HARNESS_SPEC.md "Two schema families"):

  agentforge/src/schemas.js (Zod, in the *target* repo)
    -> vendor/agentforge-schemas/*.json  (pinned snapshot; see PROVENANCE.md)
    -> src/redteam/contracts/target/*.py  (this script)

We do not import target code. The snapshot is committed here and pinned to a
target SHA; `tests/test_contracts.py` guards that the committed pydantic matches
a fresh generation from the snapshot. When the snapshot is refreshed, re-check
the target's Zod for refinements JSON Schema cannot carry (PROVENANCE.md).

Usage (from repo root): uv run python tools/generate_contracts.py [--output DIR]
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SCHEMA_DIR = REPO_ROOT / "vendor" / "agentforge-schemas"
DEFAULT_OUTPUT = REPO_ROOT / "src" / "redteam" / "contracts" / "target"

HEADER = (
    "# GENERATED by tools/generate_contracts.py - do not edit.\n"
    "# Source: vendor/agentforge-schemas/*.json (pinned target snapshot; see PROVENANCE.md)."
)

CODEGEN_ARGS = [
    "--input-file-type", "jsonschema",
    "--output-model-type", "pydantic_v2.BaseModel",
    "--target-python-version", "3.13",
    "--disable-timestamp",
    "--use-annotated",
    "--field-constraints",
    "--use-standard-collections",
    "--use-union-operator",
    "--formatters", "builtin",
    "--custom-file-header", HEADER,
]


def generate(output: Path) -> None:
    subprocess.run(
        [
            sys.executable, "-m", "datamodel_code_generator",
            "--input", str(SCHEMA_DIR),
            "--output", str(output),
            *CODEGEN_ARGS,
        ],
        check=True,
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    generate(parser.parse_args().output)


if __name__ == "__main__":
    main()
